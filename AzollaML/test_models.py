import os
import numpy as np
from ultralytics import YOLO

def calculate_coverage(result):
    """Calculates the exact percentage of the image covered by Azolla."""
    # If the model detects no plant matter, return 0%
    if result.masks is None:
        return 0.0
    
    # Extract the binary mask tensor and convert it to a NumPy array
    masks_array = result.masks.data.cpu().numpy()
    
    # The model might detect multiple fragmented patches of Azolla.
    # This combines them into one single flat layer (1 = Azolla, 0 = Water)
    combined_mask = np.any(masks_array, axis=0)
    
    # Count the Azolla pixels vs Total pixels
    azolla_pixels = np.sum(combined_mask)
    total_pixels = combined_mask.size
    
    # Calculate and return the final percentage
    coverage = (azolla_pixels / total_pixels) * 100
    return coverage

def main():
    # --- 1. Configuration ---
    # Update these paths if your files are located elsewhere
    pt_model_path = '../runs/segment/train/weights/best.pt'
    ncnn_model_path = '../runs/segment/train/weights/best_ncnn_model'
    
    # Use the test split automatically generated by your dataset tool
    test_images_dir = 'AzollaSense.v1/test/images'
    output_dir = 'test_results_visual'
    
    os.makedirs(output_dir, exist_ok=True)
    
    # --- 2. Load Models ---
    print("Loading PyTorch (.pt) Model...")
    pt_model = YOLO(pt_model_path)
    
    print("Loading NCNN Edge Model...")
    ncnn_model = YOLO(ncnn_model_path)
    
    # --- 3. Run Evaluation ---
    if not os.path.exists(test_images_dir):
        print(f"\nError: Test folder '{test_images_dir}' not found.")
        return
        
    images = [f for f in os.listdir(test_images_dir) if f.lower().endswith(('.jpg', '.png', '.jpeg'))]
    print(f"\nFound {len(images)} test images. Running inference...\n")
    
    # Print the terminal table header
    print(f"{'Filename':<25} | {'PyTorch %':<12} | {'NCNN %':<12} | {'Difference':<10}")
    print("-" * 67)
    
    for img_name in images:
        img_path = f"{test_images_dir}/{img_name}"
        
        # Run both models (verbose=False keeps the terminal output clean)
        pt_res = pt_model(img_path, verbose=False)[0]
        ncnn_res = ncnn_model(img_path, verbose=False)[0]
        
        # Calculate exact coverage percentage
        pt_cov = calculate_coverage(pt_res)
        ncnn_cov = calculate_coverage(ncnn_res)
        
        # Calculate the precision difference between formats
        diff = abs(pt_cov - ncnn_cov)
        
        # Print side-by-side comparison row
        print(f"{img_name[:23]:<25} | {pt_cov:>11.2f}% | {ncnn_cov:>11.2f}% | {diff:>9.2f}%")
        
        # Save a visual copy of the NCNN result with the mask drawn over the original photo
        ncnn_res.save(filename=f"{output_dir}/ncnn_{img_name}")
        
    print(f"\nFinished! Visual results with drawn masks saved to: {output_dir}/")

if __name__ == '__main__':
    main()